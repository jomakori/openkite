// Reports the vendored OKT-67 spike bundle sizes and refreshes SOURCE.txt.
import { gzipSync } from 'node:zlib'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const webRoot = resolve(here, '..')
const pkg = JSON.parse(readFileSync(join(webRoot, 'package.json'), 'utf8'))
const outDir = resolve(webRoot, pkg.openkite.vendoredBundleDir)
const files = ['app.js', 'app.css']

const deps = { ...pkg.dependencies, ...pkg.devDependencies }

const rows = files.map((name) => {
  const bytes = readFileSync(join(outDir, name))
  return { name, bytes: bytes.length, gzip: gzipSync(bytes).length }
})

const total = rows.reduce((sum, row) => sum + row.bytes, 0)
const totalGzip = rows.reduce((sum, row) => sum + row.gzip, 0)
const kib = (n) => (n / 1024).toFixed(2)

for (const row of rows) {
  console.log(`${row.name}: ${row.bytes} B (${kib(row.bytes)} KiB), gzip ${row.gzip} B (${kib(row.gzip)} KiB)`)
}
console.log(`total: ${total} B (${kib(total)} KiB), gzip ${totalGzip} B (${kib(totalGzip)} KiB)`)

const source = [
  'OpenKite vendored React spike bundle (OKT-67).',
  '',
  'Generated by web/scripts/bundle-size.mjs; do not edit by hand.',
  '',
  'Packages:',
  `  react@${deps.react}`,
  `  react-dom@${deps['react-dom']}`,
  `  tailwindcss@${deps.tailwindcss}`,
  `  vite@${deps.vite}`,
  '',
  'Sizes:',
  ...rows.map((row) => `  ${row.name}: ${row.bytes} B (gzip ${row.gzip} B)`),
  `  total: ${total} B (gzip ${totalGzip} B)`,
  '',
  'Rebuild:',
  '  cd web && npm install && npm run build && npm run bundle-size',
  '',
].join('\n')
writeFileSync(join(outDir, 'SOURCE.txt'), source)
console.log(`wrote ${join(outDir, 'SOURCE.txt')}`)
