#!/usr/bin/env python3
"""Generates src/table_columns.rs from the console prototype's column definitions.

The prototype declares a column list per resource kind in
docs/reference/opendesign-console/openkite-console.js. Re-typing those into Rust
guarantees drift, so they are extracted here and emitted as a const table. Run
from anywhere: paths are relative to this file.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REF = Path(__file__).resolve().parents[3] / "docs/reference/opendesign-console"
JS = REF / "openkite-console.js"
OUT = Path(__file__).resolve().parents[1] / "src/table_columns.rs"

# Prototype kind key -> catalogue kind key (nav.rs CATALOGUE).
ALIAS = {
    "deploy": "deployments",
    "deployment": "deployments",
    "sts": "statefulsets",
    "ds": "daemonsets",
    "rs": "replicasets",
    "po": "pods",
    "svc": "services",
    "ing": "ingresses",
    "cm": "configmaps",
    "netpol": "networkpolicies",
    "pvc": "pvcs",
    "pv": "pvs",
    "sa": "serviceaccounts",
    "hpa": "hpas",
    "cr": "clusterroles",
    "rb": "rolebindings",
}

READY_COLS = [
    ("name", "Name"),
    ("ns", "Namespace"),
    ("ready", "Ready"),
    ("age", "Age"),
    ("status", "Status"),
]

DEFAULT_NAMESPACED = [
    ("name", "Name"),
    ("ns", "Namespace"),
    ("status", "Status"),
    ("age", "Age"),
]
DEFAULT_CLUSTER = [("name", "Name"), ("status", "Status"), ("age", "Age")]


def value_end(src: str, start: int) -> int:
    depth = 0
    for i in range(start, len(src)):
        ch = src[i]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
            if depth == 0:
                return i + 1
    return start + 2000


def extract(src: str) -> dict[str, list[tuple[str, str]]]:
    found: dict[str, list[tuple[str, str]]] = {}
    for match in re.finditer(r"\bcols\s*:\s*", src):
        start = match.end()
        keys = list(re.finditer(r"\n\s{2,6}([a-z][a-zA-Z0-9]*)\s*:\s*\{", src[: match.start()]))
        if not keys:
            continue
        kind = keys[-1].group(1)
        if kind in found:
            continue
        segment = src[start : value_end(src, start)]
        pairs = re.findall(r"\{\s*id\s*:\s*'([^']+)'\s*,\s*label\s*:\s*'([^']+)'", segment)
        arrays = re.findall(r"\[\s*'([^']+)'\s*,\s*'([^']+)'(?:\s*,\s*'[^']*')?\s*\]", segment)
        cols: list[tuple[str, str]] = []
        seen: set[str] = set()
        for col_id, label in pairs + arrays:
            if col_id in seen:
                continue
            seen.add(col_id)
            cols.append((col_id, label))
        if not cols and "readyCols" in segment:
            cols = list(READY_COLS)
        if cols:
            found[kind] = cols
    return found


def rust_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(cols_by_kind: dict[str, list[tuple[str, str]]], kinds: list[str]) -> str:
    lines = [
        "// @generated by crates/openkite-ui/assets/build_table_columns.py — do not edit.",
        "// Source: docs/reference/opendesign-console/openkite-console.js (KINDS.*.cols).",
        "",
        "use crate::table::Column;",
        "",
        "/// Columns per catalogue kind, in prototype order. Kinds the prototype does not",
        "/// tabulate fall back to [`DEFAULT_COLUMNS`].",
        "pub const KIND_COLUMNS: &[(&str, &[Column])] = &[",
    ]
    cluster_scoped = {"nodes", "namespaces", "pvs", "storageclasses", "clusterroles", "crds"}
    for kind in kinds:
        cols = cols_by_kind.get(kind)
        if cols is None:
            cols = DEFAULT_CLUSTER if kind in cluster_scoped else DEFAULT_NAMESPACED
        entries = []
        for col_id, label in cols:
            entries.append(
                f"        Column {{ id: {rust_str(col_id)}, label: {rust_str(label)} }},"
            )
        lines.append(f"    ({rust_str(kind)}, &[")
        lines.extend(entries)
        lines.append("    ]),")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    src = JS.read_text(encoding="utf-8")
    cols_by_kind = extract(src)
    remapped: dict[str, list[tuple[str, str]]] = {}
    for kind, cols in cols_by_kind.items():
        remapped[ALIAS.get(kind, kind)] = cols
    kinds = re.findall(r'key: "([a-z0-9]+)"', (OUT.parent / "nav.rs").read_text(encoding="utf-8"))
    OUT.write_text(emit(remapped, kinds), encoding="utf-8")
    mapped = sum(1 for k in kinds if k in remapped)
    print(f"{len(kinds)} kinds, {mapped} from prototype, {len(kinds) - mapped} default")
    return 0


if __name__ == "__main__":
    sys.exit(main())
