"""Build console.css = vendored @font-face block + the three prototype stylesheets verbatim.

Rationale: surgical rule extraction repeatedly lost cascade order and @media
context (topbar geometry drifted 56 -> 65px). Concatenating the reference sheets
in their document order preserves the real cascade; selectors for surfaces the
shell does not render are inert.

The sheets are the only edit surface. `--check` renders the same concatenation
in memory and fails when it differs from the committed console.css, so CI catches
a hand-edit of the generated file instead of shipping it.
"""

import argparse
import difflib
import re
import sys
from pathlib import Path

REF = Path(__file__).resolve().parents[3] / "docs/reference/opendesign-console"
ASSETS = Path(__file__).resolve().parent
OUT = ASSETS / "console.css"
SHEETS = ["openkite-console.css", "openkite-workloads.css", "openkite-charts.css"]

TOKEN = re.compile(r"(--[a-z0-9-]+)\s*:")
COMMENT = re.compile(r"/\*.*?\*/", re.S)


def without_comments(css: str) -> str:
    """Comment-free copy, used for stats only - comments are part of the output."""
    return COMMENT.sub("", css)


def font_faces(assets: Path) -> str:
    """One @font-face per vendored woff2 (family/weight parsed from filename)."""
    faces = []
    for path in sorted((assets / "fonts").glob("*.woff2")):
        stem = path.stem  # e.g. ibm-plex-sans-400
        *family, weight = stem.split("-")
        name = " ".join(w.capitalize() for w in family)
        faces.append(
            "@font-face{font-family:'%s';font-style:normal;font-weight:%s;"
            'font-display:swap;src:url("/assets/fonts/%s") format("woff2")}'
            % (name, weight, path.name)
        )
    return "\n".join(faces)


def build(ref: Path, assets: Path) -> str:
    parts = [
        "/* Vendored fonts + verbatim concatenation of the openkite prototype",
        "   stylesheets (openkite-console.css, openkite-workloads.css,",
        "   openkite-charts.css) in document load order. Generated by",
        "   build_console_css.py - edit the reference sheets, not this file. */",
        font_faces(assets),
    ]
    for name in SHEETS:
        css = (ref / name).read_text(encoding="utf-8")
        parts.append(f"\n/* ---- {name} ---- */\n{css.strip()}\n")
    return "\n".join(parts)


def summary(out: str) -> str:
    bare = without_comments(out)
    return (
        f"sheets={len(SHEETS)} bytes={len(out)} "
        f"faces={len(re.findall(r'@font-face', bare))} "
        f"media={len(re.findall(r'@media', bare))} "
        f"tokens={len(TOKEN.findall(bare))} "
        f"brace_delta={bare.count('{') - bare.count('}')}"
    )


def dropped_tokens(existing: str, candidate: str, allowed: set[str]) -> list[str]:
    """Custom properties that only the committed output defines would vanish."""
    have = set(TOKEN.findall(without_comments(existing)))
    want = set(TOKEN.findall(without_comments(candidate)))
    return sorted(have - want - allowed)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Build console.css from the reference sheets, or check it is in sync."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="render in memory and fail when it differs from the committed file",
    )
    parser.add_argument(
        "--ref",
        type=Path,
        default=REF,
        help="directory holding the reference sheets (default: docs/reference/opendesign-console)",
    )
    parser.add_argument("--out", type=Path, default=OUT, help="generated stylesheet path")
    parser.add_argument(
        "--allow-drop",
        default="",
        metavar="TOKEN[,TOKEN]",
        help="custom properties whose removal is intended",
    )
    args = parser.parse_args(argv)

    allowed = {token.strip() for token in args.allow_drop.split(",") if token.strip()}
    candidate = build(args.ref, ASSETS)

    if args.out.exists():
        existing = args.out.read_text(encoding="utf-8")
        lost = dropped_tokens(existing, candidate, allowed)
        if lost:
            print(
                f"refusing: {args.out.name} would lose {len(lost)} custom "
                f"propert{'y' if len(lost) == 1 else 'ies'} it defines today:",
                file=sys.stderr,
            )
            for token in lost:
                print(f"  {token}", file=sys.stderr)
            print(
                "Move them into the reference sheets, or pass --allow-drop <token> "
                "when the removal is intended.",
                file=sys.stderr,
            )
            return 2

    if args.check:
        if not args.out.exists():
            print(f"missing {args.out}: run build_console_css.py", file=sys.stderr)
            return 1
        existing = args.out.read_text(encoding="utf-8")
        if existing == candidate:
            print(f"console.css in sync with the reference sheets ({summary(candidate)})")
            return 0
        diff = list(
            difflib.unified_diff(
                existing.splitlines(),
                candidate.splitlines(),
                fromfile=f"{args.out.name} (committed)",
                tofile=f"{args.out.name} (from the reference sheets)",
                lineterm="",
                n=3,
            )
        )
        print("\n".join(diff[:400]), file=sys.stderr)
        if len(diff) > 400:
            print(f"... {len(diff) - 400} more diff lines", file=sys.stderr)
        print(
            f"\nconsole.css is out of sync with the reference sheets: "
            f"{len(diff)} diff lines. Edit the sheets, then run "
            f"python3 crates/openkite-ui/assets/build_console_css.py.",
            file=sys.stderr,
        )
        return 1

    args.out.write_text(candidate, encoding="utf-8")
    print(summary(candidate))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
