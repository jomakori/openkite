"""Build console.css = vendored @font-face block + the three prototype stylesheets verbatim.

Rationale: surgical rule extraction repeatedly lost cascade order and @media
context (topbar geometry drifted 56 -> 65px). Concatenating the reference sheets
in their document order preserves the real cascade; selectors for surfaces the
shell does not render are inert.
"""

import re
from pathlib import Path

REF = Path(__file__).resolve().parents[3] / "docs/reference/opendesign-console"
ASSETS = Path(__file__).resolve().parent
OUT = ASSETS / "console.css"
SHEETS = ["openkite-console.css", "openkite-workloads.css", "openkite-charts.css"]


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def font_faces() -> str:
    """One @font-face per vendored woff2 (family/weight parsed from filename)."""
    faces = []
    for path in sorted((ASSETS / "fonts").glob("*.woff2")):
        stem = path.stem  # e.g. ibm-plex-sans-400
        *family, weight = stem.split("-")
        name = " ".join(w.capitalize() for w in family)
        faces.append(
            "@font-face{font-family:'%s';font-style:normal;font-weight:%s;"
            'font-display:swap;src:url("/assets/fonts/%s") format("woff2")}'
            % (name, weight, path.name)
        )
    return "\n".join(faces)


parts = [
    "/* Vendored fonts + verbatim concatenation of the openkite prototype",
    "   stylesheets (openkite-console.css, openkite-workloads.css,",
    "   openkite-charts.css) in document load order. Generated by",
    "   build_console_css.py - edit the reference sheets, not this file. */",
    font_faces(),
]

for name in SHEETS:
    css = strip_comments((REF / name).read_text(encoding="utf-8"))
    parts.append(f"\n/* ---- {name} ---- */\n{css.strip()}\n")

out = "\n".join(parts)
OUT.write_text(out, encoding="utf-8")

faces = len(re.findall(r"@font-face", out))
print(
    f"sheets={len(SHEETS)} bytes={len(out)} faces={faces} "
    f"media={len(re.findall(r'@media', out))} "
    f"tokens={len(re.findall(r'^\s*--[a-z0-9-]+:', out, re.M))} "
    f"brace_delta={strip_comments(out).count('{') - strip_comments(out).count('}')}"
)
